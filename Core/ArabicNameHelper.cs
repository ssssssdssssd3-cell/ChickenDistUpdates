    /// <summary>
    /// ?????? ???????????? ?????????????? ???????????? ?????????????? ?????????????? ???????? ?????????????? ???????????? ?????????????? ??????????????
    /// </summary>
    public static class ArabicNameHelper
    {
        /// <summary>
        /// ?????????? ???????????? ?????????????????? ???? ?????????? ?????????????? ???????????? ?????????????? ?????????????????? ??????????????
        /// </summary>
        public static string Normalize(string text)
        {
            if (string.IsNullOrWhiteSpace(text)) return string.Empty;

            string s = text.Trim();

            // 1. ?????????? ?????????????? (??) ?????????????? ??????????????
            s = s.Replace("\u0640", ""); // Tatweel
            s = s.Replace("\u064B", "").Replace("\u064C", "").Replace("\u064D", "")
                 .Replace("\u064E", "").Replace("\u064F", "").Replace("\u0650", "")
                 .Replace("\u0651", "").Replace("\u0652", "");

            // 2. ?????????? ?????????? ?????????? ?????????????? (???? ???? ???? ?? -> ??)
            s = s.Replace('\u0623', '\u0627')
                 .Replace('\u0625', '\u0627')
                 .Replace('\u0622', '\u0627')
                 .Replace('\u0671', '\u0627');

            // 3. ?????????? ?????????? ???????????? ???????????????? (?? -> ??)
            s = s.Replace('\u0649', '\u064A');

            // 4. ?????????? ?????????? ???????????????? ???????????? ???? ?????????? ??????????????
            s = s.Replace('\u0629', '\u0647');

            // 5. ?????????? ?????????????? (?? -> ?? ?? ?? -> ??)
            s = s.Replace('\u0624', '\u0648')
                 .Replace('\u0626', '\u064A');

            // 6. ?????? ???????????? ?????????????? ?????????????? ?????????????? ???????????? ???????????? ?????????????? (?????? ?? ?????? ?? ?????? ?? ????)
            s = s.Replace("\u0639\u0628\u062F ", "\u0639\u0628\u062F"); // ??????
            s = s.Replace("\u0627\u0628\u0648 ", "\u0627\u0628\u0648"); // ??????
            s = s.Replace("\u0623\u0628\u0648 ", "\u0627\u0628\u0648"); // ??????
            s = s.Replace("\u0627\u0628\u0646 ", "\u0627\u0628\u0646"); // ??????
            s = s.Replace("\u0628\u0646 ", "\u0628\u0646");             // ????

            // 7. ?????????? ???????????????? ????????????????
            var parts = s.Split(new[] { ' ', '\t', '\r', '\n' }, StringSplitOptions.RemoveEmptyEntries);
            return string.Join(" ", parts).ToLowerInvariant();
        }

        /// <summary>
        /// ?????????? ?????????? ???????????? ?????? ??????????
        /// </summary>
        public static string[] GetWords(string text)
        {
            string norm = Normalize(text);
            if (string.IsNullOrEmpty(norm)) return new string[0];
            return norm.Split(new[] { ' ' }, StringSplitOptions.RemoveEmptyEntries);
        }

        /// <summary>
        /// ?????????????? ?????????? ?????????????? (?????? ????????????) ?????? ??????????????
        /// </summary>
        public static string GetBinaryName(string text)
        {
            var words = GetWords(text);
            if (words.Length == 0) return string.Empty;
            if (words.Length == 1) return words[0];
            return words[0] + " " + words[1];
        }

        /// <summary>
        /// ?????? ???? ?????????? ???????????? ?????????? ?????????? ???????????? ?????????????? ???? ???????????? ??????????????
        /// </summary>
        public static bool IsDuplicate(string inputName, string existingName, out string matchReason)
        {
            matchReason = "";
            if (string.IsNullOrWhiteSpace(inputName) || string.IsNullOrWhiteSpace(existingName))
                return false;

            string normInput = Normalize(inputName);
            string normExisting = Normalize(existingName);

            // 1. ?????????? ?????? ?????? ??????????????
            if (normInput == normExisting)
            {
                matchReason = "\u062a\u0637\u0627\u0628\u0642 \u0643\u0627\u0645\u0644 \u0628\u0646\u0641\u0633 \u0627\u0644\u0627\u0633\u0645"; // ?????????? ???????? ???????? ??????????
                return true;
            }

            var inputWords = GetWords(inputName);
            var existingWords = GetWords(existingName);

            if (inputWords.Length == 0 || existingWords.Length == 0)
                return false;

            // 2. ?????? ?????? ???????????? ?????? ?????????? (????????????) ???????? ????????????????
            if (inputWords.Length == 2 && existingWords.Length == 2)
            {
                if (inputWords[0] == existingWords[0] && inputWords[1] == existingWords[1])
                {
                    matchReason = "\u062a\u0637\u0627\u0628\u0642 \u062a\u0627\u0645 \u0641\u064a \u0627\u0644\u0627\u0633\u0645 \u0627\u0644\u062b\u0646\u0627\u0626\u064a"; // ?????????? ?????? ???? ?????????? ??????????????
                    return true;
                }
            }

            // 3. ?????? ???????? ???????????????? ?????????? ?????????????? ?????? (????????????)?? ???????? ???????? ?????? ???????? ???????? ???????? ????????????????
            if (inputWords.Length == 2 && existingWords.Length >= 2)
            {
                if (inputWords[0] == existingWords[0] && inputWords[1] == existingWords[1])
                {
                    matchReason = "\u0627\u0644\u0627\u0633\u0645 \u0627\u0644\u0645\u062f\u062e\u0644 \u062b\u0646\u0627\u0626\u064a \u0648\u064a\u0637\u0627\u0628\u0642 \u0628\u062f\u0627\u064a\u0647 \u0627\u0633\u0645 \u0645\u0633\u062c\u0644 \u0645\u0633\u0628\u0642\u0627\u064b"; // ?????????? ???????????? ?????????? ???????????? ?????????? ?????? ???????? ????????????
                    return true;
                }
            }

            // 4. ?????? ?????? ?????????? ???????????? ?????????????? ?????? (????????????)?? ?????????? ???????????????? ?????????? ???????? ???????? ????????????????
            if (existingWords.Length == 2 && inputWords.Length == 2)
            {
                if (inputWords[0] == existingWords[0] && inputWords[1] == existingWords[1])
                {
                    matchReason = "\u062a\u0637\u0627\u0628\u0642 \u0645\u0639 \u0627\u0633\u0645 \u062b\u0646\u0627\u0626\u064a \u0645\u0633\u062c\u0644 \u0645\u0633\u0628\u0642\u0627\u064b"; // ?????????? ???? ?????? ?????????? ???????? ????????????
                    return true;
                }
            }

            return false;
        }
    }
